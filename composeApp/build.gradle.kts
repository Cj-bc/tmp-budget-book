// The commit and time of the build, shown in the settings. Builds without the git repository
// (Nix and the container image) pass the commit as -Pkakeibo.commit. The build time can be fixed
// with -Pkakeibo.buildTime, as an ISO-8601 instant.

/** The checked out commit, with `-dirty` appended if there are changes, or `unknown` without git. */
abstract class GitCommit : ValueSource<String, ValueSourceParameters.None> {
    @get:Inject
    abstract val exec: ExecOperations

    private fun git(vararg args: String): String {
        val output = ByteArrayOutputStream()
        exec.exec {
            commandLine("git", *args)
            standardOutput = output
            errorOutput = ByteArrayOutputStream()
        }
        return output.toString().trim()
    }

    override fun obtain(): String = runCatching {
        val commit = git("rev-parse", "HEAD")
        if (git("status", "--porcelain").isEmpty()) commit else "$commit-dirty"
    }.getOrDefault("unknown")
}

abstract class GenerateBuildInfo : DefaultTask() {
    @get:Input
    abstract val commit: Property<String>

    @get:Input
    abstract val buildTime: Property<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val file = outputDirectory.file("jp/cjbc/kakeibo/BuildInfo.kt").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package jp.cjbc.kakeibo
            |
            |/** Generated by the build: the commit it was built from, and when. */
            |internal object BuildInfo {
            |    /** The commit's hash, `-dirty` if it had changes, or `unknown`. */
            |    val commit: String = "${commit.get()}"
            |
            |    /** When the app was built, as an ISO-8601 instant. */
            |    val buildTime: String = "${buildTime.get()}"
            |}
            |""".trimMargin(),
        )
    }
}

val generateBuildInfo by tasks.registering(GenerateBuildInfo::class) {
    commit.set(providers.gradleProperty("kakeibo.commit").orElse(providers.of(GitCommit::class) {}))
    // To the minute, so that builds within the same minute don't recompile.
    buildTime.set(
        providers.gradleProperty("kakeibo.buildTime")
            .orElse(provider { Instant.now().truncatedTo(ChronoUnit.MINUTES).toString() }),
    )
    outputDirectory.set(layout.buildDirectory.dir("generated/buildInfo"))
}

